/** Parses rows of text into a TileMap; '#' is a wall, anything else floor. Short rows are padded with wall. */
export function parseMap(rows: string[]): TileMap {
  const h = rows.length;
  const w = rows.reduce((n, r) => Math.max(n, r.length), 0);
  const tiles = new Uint8Array(w * h);
  for (let z = 0; z < h; z++) for (let x = 0; x < w; x++) tiles[z * w + x] = x < rows[z].length && rows[z][x] !== '#' ? TILE_ID.Floor : TILE_ID.Wall;
  return new TileMap(w, h, tiles);
}
